import 'package:flutter_riverpod/flutter_riverpod.dart';

/// Payment methods supported by the POS checkout flow.
enum PaymentMethod {
  cash,
  qris,
  bank,
}

extension PaymentMethodX on PaymentMethod {
  String get label {
    switch (this) {
      case PaymentMethod.cash:
        return 'Tunai';
      case PaymentMethod.qris:
        return 'QRIS';
      case PaymentMethod.bank:
        return 'Bank';
    }
  }

  String get debitAccountCode {
    switch (this) {
      case PaymentMethod.cash:
        return PaymentAccountCodes.cash;
      case PaymentMethod.qris:
        return PaymentAccountCodes.qris;
      case PaymentMethod.bank:
        return PaymentAccountCodes.bank;
    }
  }

  String get debitAccountName {
    switch (this) {
      case PaymentMethod.cash:
        return 'Kas';
      case PaymentMethod.qris:
        return 'QRIS';
      case PaymentMethod.bank:
        return 'Bank';
    }
  }
}

/// Account codes explicitly supplied for the POS payment posting.
///
/// These constants must remain synchronized with docs/COA.md once the
/// repository accounting core is populated. No additional account code is
/// inferred by this service.
abstract final class PaymentAccountCodes {
  static const String cash = '1-1010';
  static const String qris = '1-1020';
  static const String bank = '1-1030';
  static const String inventory = '1-1040';
  static const String ppnPayable = '2-2010';
  static const String sales = '4-4010';
  static const String cogs = '5-5010';
}

/// Immutable checkout input.
///
/// Monetary values are stored as whole rupiah to avoid floating-point
/// rounding errors in accounting calculations.
class PaymentRequest {
  const PaymentRequest({
    required this.transactionId,
    required this.grossAmount,
    required this.discountAmount,
    required this.cogsAmount,
    required this.method,
    required this.occurredAt,
  });

  final String transactionId;
  final int grossAmount;
  final int discountAmount;
  final int cogsAmount;
  final PaymentMethod method;
  final DateTime occurredAt;

  int get taxableAmount => grossAmount - discountAmount;

  int get ppnAmount => PaymentService.calculatePpn(taxableAmount);

  int get amountDue => taxableAmount + ppnAmount;

  void validate() {
    if (transactionId.trim().isEmpty) {
      throw const PaymentValidationException(
        'ID transaksi wajib diisi.',
      );
    }
    if (grossAmount < 0) {
      throw const PaymentValidationException(
        'Nilai penjualan tidak boleh negatif.',
      );
    }
    if (discountAmount < 0) {
      throw const PaymentValidationException(
        'Diskon tidak boleh negatif.',
      );
    }
    if (discountAmount > grossAmount) {
      throw const PaymentValidationException(
        'Diskon tidak boleh melebihi nilai penjualan.',
      );
    }
    if (cogsAmount < 0) {
      throw const PaymentValidationException(
        'HPP tidak boleh negatif.',
      );
    }
  }
}

/// One debit or credit line generated by checkout.
class PaymentJournalLine {
  const PaymentJournalLine({
    required this.accountCode,
    required this.accountName,
    required this.debit,
    required this.credit,
    required this.description,
  });

  final String accountCode;
  final String accountName;
  final int debit;
  final int credit;
  final String description;

  void validate() {
    if (accountCode.trim().isEmpty) {
      throw const PaymentValidationException(
        'Kode akun jurnal wajib diisi.',
      );
    }
    if (debit < 0 || credit < 0) {
      throw const PaymentValidationException(
        'Nilai debit atau kredit tidak boleh negatif.',
      );
    }
    if (debit > 0 && credit > 0) {
      throw const PaymentValidationException(
        'Satu baris jurnal tidak boleh memiliki debit dan kredit sekaligus.',
      );
    }
    if (debit == 0 && credit == 0) {
      throw const PaymentValidationException(
        'Baris jurnal tidak boleh bernilai nol.',
      );
    }
  }
}

/// Complete balanced posting for a POS payment.
class PaymentPosting {
  PaymentPosting({
    required this.transactionId,
    required this.grossAmount,
    required this.discountAmount,
    required this.taxableAmount,
    required this.ppnAmount,
    required this.cogsAmount,
    required this.amountDue,
    required this.method,
    required this.occurredAt,
    required List<PaymentJournalLine> lines,
  }) : lines = List<PaymentJournalLine>.unmodifiable(lines);

  final String transactionId;
  final int grossAmount;
  final int discountAmount;
  final int taxableAmount;
  final int ppnAmount;
  final int cogsAmount;
  final int amountDue;
  final PaymentMethod method;
  final DateTime occurredAt;
  final List<PaymentJournalLine> lines;

  int get totalDebit =>
      lines.fold<int>(0, (sum, line) => sum + line.debit);

  int get totalCredit =>
      lines.fold<int>(0, (sum, line) => sum + line.credit);

  bool get isBalanced => totalDebit == totalCredit;

  bool matches(PaymentRequest request) {
    return transactionId == request.transactionId.trim() &&
        grossAmount == request.grossAmount &&
        discountAmount == request.discountAmount &&
        taxableAmount == request.taxableAmount &&
        ppnAmount == request.ppnAmount &&
        cogsAmount == request.cogsAmount &&
        amountDue == request.amountDue &&
        method == request.method;
  }

  void validateBalanced() {
    for (final line in lines) {
      line.validate();
    }
    if (lines.isEmpty) {
      throw const PaymentValidationException(
        'Jurnal pembayaran tidak boleh kosong.',
      );
    }
    if (!isBalanced) {
      throw UnbalancedJournalException(
        totalDebit: totalDebit,
        totalCredit: totalCredit,
      );
    }
  }
}

/// Result returned by the checkout payment service.
class PaymentResult {
  const PaymentResult({
    required this.posting,
    required this.alreadyProcessed,
  });

  final PaymentPosting posting;
  final bool alreadyProcessed;
}

/// Atomic persistence boundary used by the payment service.
///
/// Implementations must execute [operation] in one database transaction.
/// Any exception thrown by [operation] must roll back all writes. The
/// persistence layer must also enforce a unique constraint on transaction_id.
abstract interface class PaymentTransactionStore {
  Future<T> runTransaction<T>(
    Future<T> Function(PaymentTransactionSession session) operation,
  );
}

/// Persistence operations available inside one atomic payment transaction.
abstract interface class PaymentTransactionSession {
  Future<PaymentPosting?> findByTransactionId(String transactionId);

  Future<void> insert(PaymentPosting posting);
}

/// Creates balanced POS accounting entries and persists them atomically.
class PaymentService {
  const PaymentService({
    required PaymentTransactionStore store,
  }) : _store = store;

  static const int ppnRatePercent = 11;

  final PaymentTransactionStore _store;

  /// Calculates 11% PPN from the amount after discount.
  ///
  /// The result is rounded to the nearest whole rupiah using integer
  /// arithmetic, with .50 rounded upward.
  static int calculatePpn(int amountAfterDiscount) {
    if (amountAfterDiscount < 0) {
      throw const PaymentValidationException(
        'Dasar pengenaan PPN tidak boleh negatif.',
      );
    }
    return ((amountAfterDiscount * ppnRatePercent) + 50) ~/ 100;
  }

  Future<PaymentResult> process(PaymentRequest request) async {
    request.validate();

    final normalizedId = request.transactionId.trim();

    return _store.runTransaction<PaymentResult>((session) async {
      final existing = await session.findByTransactionId(normalizedId);

      if (existing != null) {
        existing.validateBalanced();

        if (!existing.matches(request)) {
          throw TransactionIdConflictException(normalizedId);
        }

        return PaymentResult(
          posting: existing,
          alreadyProcessed: true,
        );
      }

      final posting = _buildPosting(
        request: request,
        normalizedTransactionId: normalizedId,
      );

      // Balance is checked before persistence. If insertion fails or any
      // subsequent operation throws, runTransaction must roll everything back.
      posting.validateBalanced();
      await session.insert(posting);

      return PaymentResult(
        posting: posting,
        alreadyProcessed: false,
      );
    });
  }

  PaymentPosting _buildPosting({
    required PaymentRequest request,
    required String normalizedTransactionId,
  }) {
    final taxableAmount = request.taxableAmount;
    final ppnAmount = calculatePpn(taxableAmount);
    final amountDue = taxableAmount + ppnAmount;

    final lines = <PaymentJournalLine>[];

    if (amountDue > 0) {
      lines.add(
        PaymentJournalLine(
          accountCode: request.method.debitAccountCode,
          accountName: request.method.debitAccountName,
          debit: amountDue,
          credit: 0,
          description: 'Penerimaan pembayaran ${request.method.label}',
        ),
      );
    }

    if (taxableAmount > 0) {
      lines.add(
        PaymentJournalLine(
          accountCode: PaymentAccountCodes.sales,
          accountName: 'Penjualan',
          debit: 0,
          credit: taxableAmount,
          description: 'Penjualan setelah diskon',
        ),
      );
    }

    if (ppnAmount > 0) {
      lines.add(
        PaymentJournalLine(
          accountCode: PaymentAccountCodes.ppnPayable,
          accountName: 'Utang PPN',
          debit: 0,
          credit: ppnAmount,
          description: 'PPN keluaran 11%',
        ),
      );
    }

    if (request.cogsAmount > 0) {
      lines
        ..add(
          PaymentJournalLine(
            accountCode: PaymentAccountCodes.cogs,
            accountName: 'Harga Pokok Penjualan',
            debit: request.cogsAmount,
            credit: 0,
            description: 'Pengakuan HPP',
          ),
        )
        ..add(
          PaymentJournalLine(
            accountCode: PaymentAccountCodes.inventory,
            accountName: 'Persediaan',
            debit: 0,
            credit: request.cogsAmount,
            description: 'Pengurangan persediaan',
          ),
        );
    }

    if (lines.isEmpty) {
      throw const PaymentValidationException(
        'Transaksi tidak menghasilkan jurnal.',
      );
    }

    final posting = PaymentPosting(
      transactionId: normalizedTransactionId,
      grossAmount: request.grossAmount,
      discountAmount: request.discountAmount,
      taxableAmount: taxableAmount,
      ppnAmount: ppnAmount,
      cogsAmount: request.cogsAmount,
      amountDue: amountDue,
      method: request.method,
      occurredAt: request.occurredAt.toUtc(),
      lines: lines,
    );

    posting.validateBalanced();
    return posting;
  }
}

/// Riverpod factory for constructing a payment service with a concrete store.
final paymentServiceProvider =
    Provider.family<PaymentService, PaymentTransactionStore>(
  (ref, store) => PaymentService(store: store),
);

sealed class PaymentServiceException implements Exception {
  const PaymentServiceException(this.message);

  final String message;

  @override
  String toString() => message;
}

final class PaymentValidationException extends PaymentServiceException {
  const PaymentValidationException(super.message);
}

final class TransactionIdConflictException extends PaymentServiceException {
  TransactionIdConflictException(String transactionId)
      : super(
          'ID transaksi "$transactionId" sudah digunakan dengan data yang berbeda.',
        );
}

final class UnbalancedJournalException extends PaymentServiceException {
  UnbalancedJournalException({
    required this.totalDebit,
    required this.totalCredit,
  }) : super(
          'Jurnal tidak seimbang: debit Rp$totalDebit, kredit Rp$totalCredit.',
        );

  final int totalDebit;
  final int totalCredit;
}
